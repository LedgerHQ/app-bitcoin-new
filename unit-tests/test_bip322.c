static const bip322_tx_hashes_vector_t *find_vector(const char *message_str) {
    for (size_t i = 0; i < BIP322_TX_HASHES_VECTORS_COUNT; i++) {
        if (strcmp(BIP322_TX_HASHES_VECTORS[i].message_str, message_str) == 0) {
            return &BIP322_TX_HASHES_VECTORS[i];
        }
    }
    return NULL;
}

static void sha256d(const uint8_t *data, size_t len, uint8_t out[32]) {
    cx_hash_sha256(data, len, out, 32);
    cx_hash_sha256(out, 32, out, 32);
}

// Serializes the BIP-322 to_sign transaction spending to_spend_txid:0 (test-side
// reimplementation; the app never builds to_sign itself, the client does).
static size_t serialize_to_sign(const uint8_t to_spend_txid[32], uint8_t out[128]) {
    size_t off = 0;
    memset(out + off, 0, 4);  // nVersion = 0
    off += 4;
    out[off++] = 0x01;  // 1 input
    memcpy(out + off, to_spend_txid, 32);
    off += 32;
    memset(out + off, 0, 4);  // prevout index 0
    off += 4;
    out[off++] = 0x00;        // empty scriptSig
    memset(out + off, 0, 4);  // nSequence = 0
    off += 4;
    out[off++] = 0x01;        // 1 output
    memset(out + off, 0, 8);  // value 0
    off += 8;
    out[off++] = 0x01;  // OP_RETURN script
    out[off++] = 0x6a;
    memset(out + off, 0, 4);  // nLockTime = 0
    off += 4;
    return off;
}

// Registers a PSBT global map with the mock dispatcher and runs bip322_detect() on it.
// message == NULL means the PSBT_GLOBAL_GENERIC_SIGNED_MESSAGE field is absent.
static bool run_detect(mock_dispatcher_t *mock,
                       const uint8_t *message,
                       size_t message_len,
                       sign_psbt_state_t *st) {
    static const uint8_t key_tx_version[] = {PSBT_GLOBAL_TX_VERSION};
    static const uint8_t val_tx_version[] = {0x00, 0x00, 0x00, 0x00};
    static const uint8_t key_message[] = {PSBT_GLOBAL_GENERIC_SIGNED_MESSAGE};

    const uint8_t *keys[] = {key_tx_version, key_message};
    const size_t key_lens[] = {sizeof(key_tx_version), sizeof(key_message)};
    const uint8_t *values[] = {val_tx_version, message};
    const size_t value_lens[] = {sizeof(val_tx_version), message_len};

    memset(st, 0, sizeof(*st));
    mock_dispatcher_add_map(mock,
                            keys,
                            key_lens,
                            values,
                            value_lens,
                            message == NULL ? 1 : 2,
                            &st->global_map);

    return bip322_detect(mock_dispatcher_get_dc(mock), st);
}

