static void test_bip322_serialize_to_spend_layout(void **state) {
    (void) state;

    const bip322_tx_hashes_vector_t *v = find_vector("Hello World");
    assert_non_null(v);

    uint8_t out[BIP322_TO_SPEND_MAX_LEN];
    int len = bip322_serialize_to_spend(v->message_hash,
                                        v->challenge_script,
                                        v->challenge_script_len,
                                        out);

    assert_int_equal(len, sizeof(TO_SPEND_HELLO_WORLD));
    assert_memory_equal(out, TO_SPEND_HELLO_WORLD, sizeof(TO_SPEND_HELLO_WORLD));
}

static void test_bip322_serialize_to_spend_rejects_long_script(void **state) {
    (void) state;

    uint8_t long_script[MAX_PREVOUT_SCRIPTPUBKEY_LEN + 1] = {0};
    uint8_t out[BIP322_TO_SPEND_MAX_LEN];
    assert_int_equal(bip322_serialize_to_spend(BIP322_TX_HASHES_VECTORS[0].message_hash,
                                               long_script,
                                               sizeof(long_script),
                                               out),
                     -1);
}

// For every vector: the serialized to_spend hashes to the vector's to_spend txid, and so does
// the txid computed by bip322_compute_to_spend_txid().
static void test_bip322_vectors_to_spend_txid(void **state) {
    (void) state;

    for (size_t i = 0; i < BIP322_TX_HASHES_VECTORS_COUNT; i++) {
        const bip322_tx_hashes_vector_t *v = &BIP322_TX_HASHES_VECTORS[i];
        print_message("vector %zu: %s\n", i, v->message_str);

        uint8_t to_spend[BIP322_TO_SPEND_MAX_LEN];
        int len = bip322_serialize_to_spend(v->message_hash,
                                            v->challenge_script,
                                            v->challenge_script_len,
                                            to_spend);
        assert_true(len > 0);

        uint8_t txid[32];
        sha256d(to_spend, (size_t) len, txid);
        assert_memory_equal(txid, v->to_spend_txid, 32);

        memset(txid, 0, sizeof(txid));
        assert_int_equal(bip322_compute_to_spend_txid(v->message_hash,
                                                      v->challenge_script,
                                                      v->challenge_script_len,
                                                      txid),
                         0);
        assert_memory_equal(txid, v->to_spend_txid, 32);
    }
}

// For every vector: the to_sign transaction built on the txid the app computes hashes to the
// vector's to_sign txid. This is what the app's signature ultimately commits to.
static void test_bip322_vectors_to_sign_txid(void **state) {
    (void) state;

    for (size_t i = 0; i < BIP322_TX_HASHES_VECTORS_COUNT; i++) {
        const bip322_tx_hashes_vector_t *v = &BIP322_TX_HASHES_VECTORS[i];

        uint8_t to_spend_txid[32];
        assert_int_equal(bip322_compute_to_spend_txid(v->message_hash,
                                                      v->challenge_script,
                                                      v->challenge_script_len,
                                                      to_spend_txid),
                         0);

        uint8_t to_sign[128];
        size_t len = serialize_to_sign(to_spend_txid, to_sign);

        uint8_t txid[32];
        sha256d(to_sign, len, txid);
        assert_memory_equal(txid, v->to_sign_txid, 32);
    }
}

// ---------------------------------------------------------------------------
// Tests: bip322_detect() (message streaming and hashing), through the mock dispatcher
// ---------------------------------------------------------------------------

// For every vector: the message streamed from the (mock) client hashes to the vector's
// message_hash, and the resulting to_spend txid matches. Also checks the display metadata
// (plain sha256, printability) that the review screen relies on.
static void test_bip322_vectors_detect(void **state) {
    mock_dispatcher_t *mock = *state;

    for (size_t i = 0; i < BIP322_TX_HASHES_VECTORS_COUNT; i++) {
        const bip322_tx_hashes_vector_t *v = &BIP322_TX_HASHES_VECTORS[i];
        print_message("vector %zu: %s\n", i, v->message_str);

        sign_psbt_state_t st;
        assert_true(run_detect(mock, v->message, v->message_len, &st));

        assert_true(st.bip322.is_message_signing);
        assert_int_equal(st.bip322.message_length, v->message_len);
        assert_memory_equal(st.bip322.message_hash, v->message_hash, 32);

        uint8_t expected_sha256[32];
        cx_hash_sha256(v->message, v->message_len, expected_sha256, 32);
        assert_memory_equal(st.bip322.message_sha256, expected_sha256, 32);

        // printable iff every byte is printable ASCII (the UTF-8 vector is not)
        bool expected_printable = true;
        for (size_t j = 0; j < v->message_len; j++) {
            if (v->message[j] < 0x20 || v->message[j] > 0x7E) expected_printable = false;
        }
        assert_int_equal(st.bip322.message_printable, expected_printable);

        uint8_t txid[32];
        assert_int_equal(bip322_compute_to_spend_txid(st.bip322.message_hash,
                                                      v->challenge_script,
                                                      v->challenge_script_len,
                                                      txid),
                         0);
        assert_memory_equal(txid, v->to_spend_txid, 32);
    }
}

// A PSBT without the field is not a message signing request.
static void test_bip322_detect_absent_field(void **state) {
    mock_dispatcher_t *mock = *state;

    sign_psbt_state_t st;
    assert_true(run_detect(mock, NULL, 0, &st));
    assert_false(st.bip322.is_message_signing);
}

// Line feeds are allowed in a displayable message; other control characters are not.
static void test_bip322_detect_printability(void **state) {
    mock_dispatcher_t *mock = *state;

    static const uint8_t with_newline[] = "two\nlines";
    static const uint8_t with_control[] = "bell\x07";

    sign_psbt_state_t st;
    assert_true(run_detect(mock, with_newline, sizeof(with_newline) - 1, &st));
    assert_true(st.bip322.is_message_signing);
    assert_true(st.bip322.message_printable);

    assert_true(run_detect(mock, with_control, sizeof(with_control) - 1, &st));
    assert_true(st.bip322.is_message_signing);
    assert_false(st.bip322.message_printable);
}

